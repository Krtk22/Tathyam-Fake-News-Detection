# Training evaluation function
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score

EPOCHS = 3

results = []

def train_and_evaluate(model_name, build_fn, train_ds, test_ds, split_name):

    print(f"\n{'='*60}")
    print(f"Training {model_name} ({split_name})")
    print(f"{'='*60}")

    model = build_fn()

    early_stop = tf.keras.callbacks.EarlyStopping(
        monitor="val_loss",
        patience=2,
        restore_best_weights=True
    )

    lr_scheduler = tf.keras.callbacks.ReduceLROnPlateau(
        monitor="val_loss",
        factor=0.5,
        patience=1,
        min_lr=1e-6,
        verbose=1
    )

    history = model.fit(
        train_ds,
        validation_data=test_ds,
        epochs=EPOCHS,
        callbacks=[early_stop, lr_scheduler],
        verbose=1
    )
    # ----------------------------------------

    # Predictions
    y_true = []
    y_pred = []

    for images, labels in test_ds:
        preds = model.predict(images, verbose=0)
        y_true.extend(labels.numpy())
        y_pred.extend((preds > 0.5).astype(int).flatten())

    accuracy = accuracy_score(y_true, y_pred)
    precision = precision_score(y_true, y_pred)
    recall = recall_score(y_true, y_pred)
    f1 = f1_score(y_true, y_pred)

    results.append({
        "Model": model_name,
        "Split": split_name,
        "Accuracy": accuracy,
        "Precision": precision,
        "Recall": recall,
        "F1 Score": f1
    })

    print(f"\nAccuracy : {accuracy:.4f}")
    print(f"Precision: {precision:.4f}")
    print(f"Recall   : {recall:.4f}")
    print(f"F1 Score : {f1:.4f}")

    return history

# Training models
splits = {
    "80-20": (train80_ds, test20_ds),
    "70-30": (train70_ds, test30_ds)
}

for split_name, (train_ds, test_ds) in splits.items():

    for model_name, build_fn in models_dict.items():

        train_and_evaluate(
            model_name,
            build_fn,
            train_ds,
            test_ds,
            split_name
        )

