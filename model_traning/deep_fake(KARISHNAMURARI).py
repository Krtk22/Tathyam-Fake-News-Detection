# Tenserflow dataset
IMG_SIZE = (224,224)
BATCH_SIZE = 32
AUTOTUNE = tf.data.AUTOTUNE

def process_image(path, label, augment=False):
    image = tf.io.read_file(path)
    image = tf.image.decode_jpeg(image, channels=3)
    image = tf.image.resize(image, IMG_SIZE)

    # --- ADDING PREPROCESSING & AUGMENTATION HERE ---
    if augment:
        image = tf.image.random_flip_left_right(image)
        image = tf.image.random_brightness(image, max_delta=0.2)
        image = tf.image.random_contrast(image, lower=0.8, upper=1.2)
    # -----------------------------------------------

    image = image / 255.0
    return image, label

def create_dataset(df, shuffle=True, augment=False):
    ds = tf.data.Dataset.from_tensor_slices(
        (
            df["filepath"].values,
            df["label"].values.astype(np.float32)
        )
    )

    # Pass the augment flag into process_image using a lambda function
    ds = ds.map(lambda x, y: process_image(x, y, augment=augment),
                num_parallel_calls=AUTOTUNE)

    if shuffle:
        ds = ds.shuffle(1000)

    ds = ds.batch(BATCH_SIZE)
    ds = ds.prefetch(AUTOTUNE)

    return ds

# For 80-20 split (augment=True for train, False for test)
train80_ds = create_dataset(train80, shuffle=True, augment=True)
